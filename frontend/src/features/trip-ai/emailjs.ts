import { z } from 'zod';

const configuration = z.strictObject({serviceId:z.string().trim().min(1).max(200),templateId:z.string().trim().min(1).max(200),publicKey:z.string().trim().min(1).max(200)});
export type EmailConfig = z.infer<typeof configuration>;
export function readEmailConfig(env: Record<string,string|undefined>): EmailConfig | null {
  if (env.VITE_AI_EMAILJS_ENABLED !== 'true') return null;
  const parsed=configuration.safeParse({serviceId:env.VITE_AI_EMAILJS_SERVICE_ID,templateId:env.VITE_AI_EMAILJS_TEMPLATE_ID,publicKey:env.VITE_AI_EMAILJS_PUBLIC_KEY});
  return parsed.success ? parsed.data : null;
}
/** Timestamp for email templates, generated by the host when submission is confirmed. */
export function formatEmailTime(date: Date): string {
  const parts=new Intl.DateTimeFormat('en-CA',{timeZone:'Asia/Taipei',year:'numeric',month:'2-digit',day:'2-digit',hour:'2-digit',minute:'2-digit',second:'2-digit',hourCycle:'h23'}).formatToParts(date);
  const value=(type: string)=>parts.find(part=>part.type===type)!.value;
  return `${value('year')}/${value('month')}/${value('day')} ${value('hour')}:${value('minute')}:${value('second')}`;
}
/** Public browser credentials only. Recipient is fixed in the EmailJS dashboard template. */
export function createEmailSender(config: EmailConfig, fetcher: typeof fetch = fetch, now=Date.now, timeoutMs=15000) {
  const fixed=configuration.parse(config);
  let nextAttempt=0;
  return { async send(params: Record<string,string>, signal: AbortSignal) {
    signal.throwIfAborted();
    if (new TextEncoder().encode(JSON.stringify(params)).byteLength > 45000) throw new Error('郵件內容過長。');
    if (now()<nextAttempt) throw new Error('請稍後再寄送，避免重複提交。');
    nextAttempt=now()+60000;
    const controller=new AbortController();
    const abort=()=>controller.abort();
    signal.addEventListener('abort',abort,{once:true});
    const timer=setTimeout(abort,timeoutMs);
    try {
      const response=await fetcher('https://api.emailjs.com/api/v1.0/email/send',{
        method:'POST',headers:{'Content-Type':'application/json'},signal:controller.signal,
        body:JSON.stringify({service_id:fixed.serviceId,template_id:fixed.templateId,user_id:fixed.publicKey,template_params:params}),
      });
      controller.signal.throwIfAborted();
      const text=(await response.text()).trim();
      controller.signal.throwIfAborted();
      if (response.status!==200 || !['OK','"OK"'].includes(text)) throw new Error('郵件服務未確認接受寄送。');
    } finally { clearTimeout(timer);signal.removeEventListener('abort',abort); }
  } };
}
